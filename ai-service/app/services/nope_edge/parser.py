"""Robust parser for NOPE Edge XML-structured model responses."""

import re
import xml.etree.ElementTree as ET

from app.services.nope_edge.schemas import RiskItem

REQUIRED_RISK_ATTRIBUTES = ("subject", "type", "severity", "imminence")


class NOPEParserError(Exception):
    """Base exception for parsing failures in NOPE Edge model output."""


class NOPEMissingRisksSectionError(NOPEParserError):
    """Raised when the mandatory <risks> block is completely absent."""


class NOPEMalformedXMLError(NOPEParserError):
    """Raised when the XML content inside <risks> is syntactically invalid or corrupt."""


class NOPERiskValidationError(NOPEParserError):
    """Raised when a <risk> element fails validation (e.g. missing required attributes)."""


class NOPEOutputParser:
    """Parses and validates XML-like structured output from NOPE Edge.

    Guarantees:
    - Never uses <reflection> contents to deduce or alter risk evaluations.
    - Treats all LLM output as untrusted and potentially malformed.
    - Never misinterprets a parse failure as a 'safe / no risk' signal.
    """

    # Matches markdown fences such as ```xml ... ``` or ``` ... ```
    _MARKDOWN_BLOCK_RE = re.compile(r"```(?:xml)?\s*(.*?)\s*```", re.DOTALL | re.IGNORECASE)

    # Matches <reflection>...</reflection>
    _REFLECTION_RE = re.compile(r"<reflection>(.*?)</reflection>", re.DOTALL | re.IGNORECASE)

    # Matches self-closing <risks/> or <risks />
    _SELF_CLOSING_RISKS_RE = re.compile(r"<risks\s*/>", re.IGNORECASE)

    # Matches <risks ...>...</risks>
    _RISKS_BLOCK_RE = re.compile(r"<risks\b[^>]*>(.*?)</risks>", re.DOTALL | re.IGNORECASE)

    # Regex to escape unescaped ampersands in XML attributes or text
    _UNESCAPED_AMP_RE = re.compile(r"&(?!amp;|lt;|gt;|quot;|apos;|#\d+;|#x[0-9a-fA-F]+;)")

    def parse(self, raw_output: str) -> tuple[list[RiskItem], str | None]:
        """Extract risks and optional reflection text from the model output.

        Args:
            raw_output: Raw text generated by the NOPE Edge model.

        Returns:
            A tuple of (list of validated RiskItems, optional reflection string).

        Raises:
            NOPEMissingRisksSectionError: When no <risks> section is located.
            NOPEMalformedXMLError: When XML syntax within <risks> cannot be parsed.
            NOPERiskValidationError: When a <risk> element lacks mandatory attributes.
        """
        if not raw_output or not raw_output.strip():
            raise NOPEMissingRisksSectionError("Model generated empty output; missing <risks> section.")

        # Strip markdown fences if present
        cleaned_text = raw_output.strip()
        md_match = self._MARKDOWN_BLOCK_RE.search(cleaned_text)
        if md_match:
            # Use fenced content if it contains <risks>, otherwise keep whole text
            candidate = md_match.group(1).strip()
            if "<risks" in candidate:
                cleaned_text = candidate

        # 1. Extract <reflection> for auditing (strictly NOT for automated decisions)
        reflection: str | None = None
        refl_match = self._REFLECTION_RE.search(cleaned_text)
        if refl_match:
            reflection = refl_match.group(1).strip()

        # 2. Check for self-closing <risks/> tag (explicit confirmation of zero risks)
        if self._SELF_CLOSING_RISKS_RE.search(cleaned_text):
            return [], reflection

        # 3. Locate <risks>...</risks> block
        risks_match = self._RISKS_BLOCK_RE.search(cleaned_text)
        if not risks_match:
            raise NOPEMissingRisksSectionError(
                "Model output is missing mandatory <risks>...</risks> section."
            )

        risks_content = risks_match.group(1).strip()

        # Empty body inside <risks></risks> signifies zero detected risks
        if not risks_content:
            return [], reflection

        # 4. Parse XML content safely
        sanitized_xml = self._UNESCAPED_AMP_RE.sub("&amp;", risks_content)
        wrapped_xml = f"<root>{sanitized_xml}</root>"

        try:
            root = ET.fromstring(wrapped_xml)
        except ET.ParseError as exc:
            raise NOPEMalformedXMLError(
                f"Failed to parse XML in <risks> section: {exc}"
            ) from exc

        # 5. Extract and validate each child element
        risks: list[RiskItem] = []
        for child in root:
            tag_name = child.tag.lower()
            if tag_name != "risk":
                raise NOPEMalformedXMLError(
                    f"Unexpected XML element <{child.tag}> inside <risks> section. Only <risk> is permitted."
                )

            # Lowercase attribute keys for uniform access
            attributes = {k.lower(): (v.strip() if v else "") for k, v in child.attrib.items()}

            # Validate presence of all required attributes
            missing_attrs = [req for req in REQUIRED_RISK_ATTRIBUTES if not attributes.get(req)]
            if missing_attrs:
                raise NOPERiskValidationError(
                    f"Risk element is missing required attribute(s): {', '.join(missing_attrs)}"
                )

            # Parse features (comma-separated or empty)
            raw_features = attributes.get("features", "")
            features_list = [f.strip() for f in raw_features.split(",") if f.strip()]

            risk_item = RiskItem(
                subject=attributes["subject"],
                type=attributes["type"],
                severity=attributes["severity"],
                imminence=attributes["imminence"],
                features=features_list,
                raw_attributes=dict(child.attrib),
            )
            risks.append(risk_item)

        return risks, reflection
